// Writes src/icons/lucide.generated.ts: one import per `lucide:<name>` the
// collections under backend/collections reference (view.yaml, source.yaml,
// data/*.yaml, seeds), plus the fallbacks. A static map keeps the bundle to
// the icons the repo uses instead of all of lucide-react.
//
//   npm run generate:icons -w @jsudc/frontend
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import * as lucide from "lucide-react";

const FRONTEND = fileURLToPath(new URL("..", import.meta.url));
const COLLECTIONS = join(FRONTEND, "..", "backend", "collections");
const OUT = join(FRONTEND, "src", "icons", "lucide.generated.ts");
/** Always present: the fallback, and the default icon of a collection node. */
const ALWAYS = ["circle", "table"];
const REF_RE = /lucide:([a-z0-9]+(?:-[a-z0-9]+)*)/g;
const SCANNED = /\.(ya?ml|json)$/;

function* files(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* files(path);
    else if (SCANNED.test(name)) yield path;
  }
}

const pascal = (kebab) =>
  kebab
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const names = new Set(ALWAYS);
for (const file of files(COLLECTIONS)) {
  for (const [, name] of readFileSync(file, "utf8").matchAll(REF_RE)) names.add(name);
}

const exported = new Set(Object.keys(lucide));
const known = [];
for (const name of [...names].sort()) {
  const icon = `${pascal(name)}Icon`;
  if (exported.has(icon)) known.push([name, icon]);
  else console.warn(`lucide:${name}: lucide-react has no ${icon}; it will draw the fallback`);
}

const source = `// Generated by scripts/generate-icons.mjs from the lucide:<name> references under
// ${relative(join(FRONTEND, ".."), COLLECTIONS)}. Do not edit: run \`npm run generate:icons -w @jsudc/frontend\`.
import {
${known.map(([, exported]) => `  ${exported},`).join("\n")}
  type LucideIcon,
} from "lucide-react";

export const LUCIDE_ICONS: Readonly<Record<string, LucideIcon>> = {
${known.map(([name, exported]) => `  ${name.includes("-") ? JSON.stringify(name) : name}: ${exported},`).join("\n")}
};
`;
writeFileSync(OUT, source);
console.log(`${relative(FRONTEND, OUT)}: ${known.length} icons`);
